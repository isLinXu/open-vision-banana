#!/usr/bin/env python3
"""LoRA inference & validation — generate images with trained LoRA weights on MPS.

Loads segmind/tiny-sd base model, applies trained LoRA adapter, and generates
comparison images: base model (no LoRA) vs LoRA-enhanced model, using COCO128
captions. Also generates a loss curve plot from training_log.json.

Output:
  - base_*.png: images generated by base model (no LoRA)
  - lora_*.png: images generated with LoRA adapter applied
  - loss_curve.png: training loss curve
  - results_summary.json: summary of generation results
"""

from __future__ import annotations

import json
import logging
import os
import time
from pathlib import Path

import numpy as np
import torch
from PIL import Image

# HuggingFace mirror
os.environ.setdefault("HF_ENDPOINT", "https://hf-mirror.com")

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger("lora_infer")

# ─── Config ──────────────────────────────────────────────────────────────
MODEL_ID = "segmind/tiny-sd"
LORA_PATH = Path(
    "/Users/gatilin/PycharmProjects/open-vision-banana/output/2060393a-ea3e-4780-9b1e-dd103a554755/lora_output/lora_final.pt"
)
TRAINING_LOG = LORA_PATH.parent / "training_log.json"
OUTPUT_DIR = LORA_PATH.parent / "validation"
DATA_DIR = Path("/Users/gatilin/PycharmProjects/open-vision-banana/data/coco128")
SEED = 42
NUM_INFERENCE_STEPS = 20  # tiny-sd is fast, 20 steps is sufficient
GUIDANCE_SCALE = 7.5
NUM_SAMPLES = 6  # number of caption-image pairs to generate


def load_coco_captions(n: int = NUM_SAMPLES) -> list[str]:
    """Load sample captions from COCO128 dataset."""
    captions_path = DATA_DIR / "captions.json"
    with open(captions_path) as f:
        pairs = json.load(f)
    # Pick evenly spaced samples for diversity
    indices = np.linspace(0, len(pairs) - 1, n, dtype=int)
    return [pairs[i]["caption"] for i in indices]


def generate_image(pipe, prompt: str, seed: int) -> Image.Image:
    """Generate a single image with the pipeline."""
    generator = torch.manual_seed(seed)
    image = pipe(
        prompt,
        num_inference_steps=NUM_INFERENCE_STEPS,
        guidance_scale=GUIDANCE_SCALE,
        generator=generator,
    ).images[0]
    return image


def apply_lora(unet, lora_state: dict):
    """Load LoRA weights into the UNet's attention modules."""
    from peft import LoraConfig, get_peft_model

    lora_config = LoraConfig(
        r=8,
        lora_alpha=16,
        target_modules=["to_q", "to_v", "to_k", "to_out.0"],
        lora_dropout=0.0,
        bias="none",
    )
    unet = get_peft_model(unet, lora_config)

    # Remap saved keys (peft model wraps with "base_model.model." prefix)
    for name, param in unet.named_parameters():
        if param.requires_grad:
            # The saved keys match the peft model's parameter names
            if name in lora_state:
                param.data.copy_(lora_state[name])
            else:
                # Try stripping/adding prefix
                # Saved keys may or may not have "base_model.model." prefix
                # Try both directions
                stripped = name.replace("base_model.model.", "")
                if stripped in lora_state:
                    param.data.copy_(lora_state[stripped])
                else:
                    prefixed = f"base_model.model.{name}"
                    if prefixed in lora_state:
                        param.data.copy_(lora_state[prefixed])
                    else:
                        logger.warning(f"Missing LoRA key: {name}")

    logger.info(f"LoRA weights loaded successfully ({len(lora_state)} keys)")
    return unet


def plot_loss_curve(log_path: Path, output_path: Path):
    """Generate a loss curve plot from training log."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    with open(log_path) as f:
        log = json.load(f)

    metrics = log["metrics"]
    steps = [m["step"] for m in metrics]
    losses = [m["loss"] for m in metrics]
    epochs = [m["epoch"] for m in metrics]

    fig, ax = plt.subplots(figsize=(10, 5), dpi=150)
    ax.plot(steps, losses, "b-o", linewidth=2, markersize=5, label="Training Loss")
    ax.fill_between(steps, losses, alpha=0.15, color="blue")

    # Mark epoch boundaries
    prev_epoch = 0
    for s, e, _l in zip(steps, epochs, losses, strict=False):
        if e != prev_epoch:
            ax.axvline(x=s, color="gray", linestyle="--", alpha=0.4)
            ax.text(s, max(losses) * 0.95, f"Epoch {e}", fontsize=8, ha="center", color="gray")
            prev_epoch = e

    ax.set_xlabel("Optimizer Step", fontsize=12)
    ax.set_ylabel("Loss (MSE)", fontsize=12)
    ax.set_title("LoRA Training Loss — tiny-sd on COCO128 (MPS)", fontsize=14, fontweight="bold")
    ax.legend(fontsize=11)
    ax.grid(True, alpha=0.3)
    ax.set_xlim(0, max(steps) + 2)

    # Annotate first and last loss
    ax.annotate(f"{losses[0]:.4f}", (steps[0], losses[0]), textcoords="offset points",
                xytext=(10, 10), fontsize=9, color="blue")
    ax.annotate(f"{losses[-1]:.4f}", (steps[-1], losses[-1]), textcoords="offset points",
                xytext=(-30, -15), fontsize=9, color="blue")

    plt.tight_layout()
    plt.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close()
    logger.info(f"Loss curve saved to {output_path}")


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    device = torch.device("mps" if torch.backends.mps.is_available() else "cpu")
    logger.info(f"Device: {device}")
    logger.info(f"Output: {OUTPUT_DIR}")

    # ── Load base pipeline ───────────────────────────────────────────
    from diffusers import StableDiffusionPipeline

    logger.info("Loading base model (segmind/tiny-sd)...")
    pipe = StableDiffusionPipeline.from_pretrained(
        MODEL_ID,
        torch_dtype=torch.float32,
        safety_checker=None,
        requires_safety_checker=False,
    )
    pipe = pipe.to(device)
    logger.info("Base model loaded")

    # ── Load captions ────────────────────────────────────────────────
    captions = load_coco_captions(NUM_SAMPLES)
    logger.info(f"Loaded {len(captions)} captions for validation")

    # ── Generate BASE images (no LoRA) ───────────────────────────────
    results = []
    for i, caption in enumerate(captions):
        t0 = time.time()
        img = generate_image(pipe, caption, seed=SEED + i)
        img_path = OUTPUT_DIR / f"base_{i:02d}.png"
        img.save(img_path)
        elapsed = time.time() - t0
        logger.info(f"[BASE {i+1}/{NUM_SAMPLES}] \"{caption[:60]}...\" → {img_path.name} ({elapsed:.1f}s)")
        results.append({"type": "base", "index": i, "caption": caption, "image": img_path.name, "time_s": round(elapsed, 1)})

    # ── Apply LoRA and generate LoRA images ──────────────────────────
    logger.info(f"Loading LoRA weights from {LORA_PATH}...")
    lora_state = torch.load(LORA_PATH, map_location="cpu")

    # Rebuild pipeline with LoRA
    pipe_lora = StableDiffusionPipeline.from_pretrained(
        MODEL_ID,
        torch_dtype=torch.float32,
        safety_checker=None,
        requires_safety_checker=False,
    )
    pipe_lora = pipe_lora.to(device)

    # Apply LoRA to UNet
    pipe_lora.unet = apply_lora(pipe_lora.unet, lora_state)
    pipe_lora.unet.eval()

    for i, caption in enumerate(captions):
        t0 = time.time()
        img = generate_image(pipe_lora, caption, seed=SEED + i)
        img_path = OUTPUT_DIR / f"lora_{i:02d}.png"
        img.save(img_path)
        elapsed = time.time() - t0
        logger.info(f"[LoRA {i+1}/{NUM_SAMPLES}] \"{caption[:60]}...\" → {img_path.name} ({elapsed:.1f}s)")
        results.append({"type": "lora", "index": i, "caption": caption, "image": img_path.name, "time_s": round(elapsed, 1)})

    # ── Generate loss curve ──────────────────────────────────────────
    loss_path = OUTPUT_DIR / "loss_curve.png"
    plot_loss_curve(TRAINING_LOG, loss_path)

    # ── Save results summary ─────────────────────────────────────────
    with open(TRAINING_LOG) as f:
        train_log = json.load(f)

    summary = {
        "model": MODEL_ID,
        "lora_path": str(LORA_PATH),
        "config": {
            "num_inference_steps": NUM_INFERENCE_STEPS,
            "guidance_scale": GUIDANCE_SCALE,
            "seed": SEED,
            "num_samples": NUM_SAMPLES,
        },
        "training": {
            "initial_loss": train_log["metrics"][0]["loss"],
            "final_loss": train_log["final_loss"],
            "total_steps": train_log["total_steps"],
            "epochs": train_log["config"]["epochs"],
            "lora_rank": train_log["config"]["lora_rank"],
            "loss_reduction_pct": round(
                (1 - train_log["final_loss"] / train_log["metrics"][0]["loss"]) * 100, 1
            ),
        },
        "generations": results,
    }

    summary_path = OUTPUT_DIR / "results_summary.json"
    with open(summary_path, "w") as f:
        json.dump(summary, f, indent=2)

    logger.info(f"\n{'='*60}")
    logger.info("Validation complete!")
    logger.info(f"  Base images:   {OUTPUT_DIR}/base_*.png")
    logger.info(f"  LoRA images:   {OUTPUT_DIR}/lora_*.png")
    logger.info(f"  Loss curve:    {loss_path}")
    logger.info(f"  Summary:       {summary_path}")
    logger.info(f"  Loss: {summary['training']['initial_loss']:.4f} → {summary['training']['final_loss']:.4f} "
                f"({summary['training']['loss_reduction_pct']}% reduction)")
    logger.info(f"{'='*60}")


if __name__ == "__main__":
    main()
